#!/usr/bin/env python3
"""Generate C include tables from the windows-syscalls CSVs.

Output: build/syscalls.inc — per-subsystem, per-architecture arrays of
{name, number-per-windows-release} plus the release-name array.

The numbers are *reference data* for diagnostics (anti-cheat research,
Wine/Proton debugging, syscall tracing). They are not used to implement
any NT kernel behavior.
"""
import csv
import os
import sys

REPO = os.path.join(os.path.dirname(__file__), "..", "windows-syscalls")

# Column that holds the newest release in each CSV (last column).
def read_csv(path):
    with open(path, newline="") as f:
        rows = list(csv.reader(f))
    header = rows[0]
    releases = header[1:]
    out = []
    for r in rows[1:]:
        if not r or not r[0]:
            continue
        out.append((r[0], r[1:]))
    return releases, out


def emit(out, subsystem, arch, releases, data):
    out.write(f'static const char *const rel_{subsystem}_{arch}[] = {{\n')
    for rel in releases:
        out.write(f'    "{rel}",\n')
    out.write('    NULL,\n};\n')
    out.write(
        f"static const NtSyscall tab_{subsystem}_{arch}[] = {{\n"
    )
    for name, nums in data:
        vals = ", ".join(n if n.strip() else "0" for n in nums)
        out.write(f'    {{ "{name}", {{ {vals} }} }},\n')
    out.write('    { NULL, { 0 } },\n};\n')


def main():
    out_path = sys.argv[1]
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, "w") as out:
        out.write(
            "/* Generated by tools/gen_syscalls.py from windows-syscalls CSVs.\n"
            " * Reference data only — NT syscall numbering is build-specific.\n"
            " */\n"
            "typedef struct { const char *name; unsigned short num[64]; } NtSyscall;\n"
        )
        for subsystem in ("nt", "win32k"):
            for arch in ("x64", "x86"):
                path = os.path.join(REPO, arch, "csv", f"{subsystem}.csv")
                releases, data = read_csv(path)
                assert len(releases) <= 64, "raise num[64] cap"
                emit(out, subsystem, arch, releases, data)
                print(f"  {subsystem}/{arch}: {len(data)} syscalls, {len(releases)} releases")


if __name__ == "__main__":
    main()
