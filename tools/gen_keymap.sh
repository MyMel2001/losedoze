#!/bin/sh
# gen_keymap.sh — build-time XKB keymap string for wl_keyboard.keymap (XKB_V1).
# Needs xkbcomp + XKB data (host has both). Output: shell/keymap.h with
# `static const char lost_xkb_keymap[]` (NUL-terminated, ready for memfd).
set -e
OUT="${1:-shell/keymap.h}"
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

# Same include set X clients get from "us" layout, evdev keycodes (xkb = evdev+8).
cat > "$TMP/km.xkb" <<'EOF'
xkb_keymap {
    xkb_keycodes "evdev" { include "evdev+aliases(qwerty)" };
    xkb_types "complete" { include "complete" };
    xkb_compatibility "complete" { include "complete" };
    xkb_symbols "pc" { include "pc+us+inet(evdev)" };
    xkb_geometry "pc" { include "pc(pc104)" };
};
EOF

if command -v xkbcomp >/dev/null 2>&1 && [ -d /usr/share/X11/xkb ]; then
    xkbcomp -w 0 -xkb -I/usr/share/X11/xkb "$TMP/km.xkb" "$TMP/km.out.xkb"
else
    echo "gen_keymap: xkbcomp or XKB data missing" >&2
    exit 1
fi

{
    echo "/* Generated by tools/gen_keymap.sh — do not edit. */"
    echo "#ifndef LOST_KEYMAP_H"
    echo "#define LOST_KEYMAP_H"
    echo "static const char lost_xkb_keymap[] ="
    # escape into a C string, one line per input line
    sed -e 's/\\/\\\\/g' -e 's/"/\\"/g' -e 's/\t/\\t/g' "$TMP/km.out.xkb" \
        | awk '{ printf "    \"%s\\n\"\n", $0 }'
    echo "    ;"
    echo "#endif"
} > "$OUT"
echo "gen_keymap: wrote $OUT ($(wc -c < "$TMP/km.out.xkb") bytes of keymap)"
