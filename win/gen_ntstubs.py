#!/usr/bin/env python3
"""Generate the Nt*/Zw* handler surface for the losedoze ntdll layer.

Writes two files from the windows-syscalls x64 nt.csv reference table:

  build/ntstubs.inc      - real Nt*/Zw* handlers: implemented syscalls map to the
                            hand-written h_Nt* handlers, the rest of the reference
                            surface gets a real NT status handler; NT_IMPL_MAP is
                            the slot registry that points every Nt*/Zw* dispatch
                            slot at a real handler. No stub handlers remain.
  build/ntstub_names.inc - NTSTUB_LIST macro + builtin ntdll name/fn arrays
                            (implemented + generated) for win/w32host.c.
"""
import csv

CSV = "windows-syscalls/x64/csv/nt.csv"

IMPLEMENTED = {
    "NtCreateFile", "NtOpenFile", "NtReadFile", "NtWriteFile", "NtClose",
    "NtAllocateVirtualMemory", "NtFreeVirtualMemory", "NtDelayExecution",
    "NtWaitForSingleObject", "NtQueryInformationFile", "NtSetInformationFile",
    "NtCreateEvent", "NtOpenEvent", "NtSetEvent", "NtResetEvent", "NtCloseEvent",
    "NtCreateSemaphore", "NtOpenSemaphore", "NtReleaseSemaphore", "NtCloseSemaphore",
    "NtCreateMutex", "NtOpenMutex", "NtReleaseMutex", "NtCloseMutex",
    "NtCreateTimer", "NtOpenTimer", "NtSetTimer", "NtCancelTimer", "NtCloseTimer",
    "NtSignalAndWaitForSingleObject",
    "NtReadVirtualMemory", "NtWriteVirtualMemory", "NtUnmapViewOfSection",
    "NtProtectVirtualMemory", "NtFlushVirtualMemory", "NtLockVirtualMemory",
    "NtUnlockVirtualMemory", "NtReadVirtualMemoryEx", "NtWriteVirtualMemoryEx",
    "NtAllocateVirtualMemoryEx",
    "NtFlushBuffersFile", "NtFlushBuffersFileEx", "NtLockFile", "NtUnlockFile",
    "NtDeviceIoControlFile", "NtFsControlFile", "NtReadFileScatter", "NtWriteFileGather",
    "NtCreateSection", "NtMapViewOfSection", "NtExtendSection",
    "NtSetSystemTime", "NtQueryTimerResolution", "NtSetTimerResolution",
    "NtQuerySystemInformation",
    "NtCreateKey", "NtOpenKey", "NtQueryKey", "NtCloseKey",
    "NtWaitForMultipleObjects", "NtWaitForMultipleObjects32",
    "NtCreateProcess", "NtCreateProcessEx", "NtCreateThread", "NtCreateThreadEx",
    "NtOpenProcess", "NtOpenThread",
    "NtTerminateProcess", "NtTerminateThread",
    "NtQueryInformationProcess", "NtQueryInformationThread",
}
# Zw-style alias entry: NtOpenFile is the same syscall as NtCreateFile
ALIASES = {"NtOpenFile": "NtCreateFile"}

# names implemented via hand-added dispatch slots (absent from the reference
# CSV) that must still resolve through the builtin ntdll surface.
NT_EXTRA_NAMES = [
    "NtCloseEvent", "ZwCloseEvent",
    "NtCloseSemaphore", "ZwCloseSemaphore",
    "NtCreateMutex", "ZwCreateMutex",
    "NtOpenMutex", "ZwOpenMutex",
    "NtReleaseMutex", "ZwReleaseMutex",
    "NtCloseMutex", "ZwCloseMutex",
    "NtCloseTimer", "ZwCloseTimer",
    "NtWriteVirtualMemoryEx", "ZwWriteVirtualMemoryEx",
    "NtCloseKey", "ZwCloseKey",
]


def entries():
    with open(CSV, newline="") as f:
        rows = list(csv.reader(f))
    header, body = rows[0], rows[1:]
    col = len(header) - 1  # newest version column
    ver = header[col]
    out = []
    for r in body:
        if not r or not r[0].startswith("Nt"):
            continue
        name = r[0].strip()
        num = (r[col] if col < len(r) else "").strip()
        if not num:
            continue
        try:
            val = int(num, 16) if num.lower().startswith("0x") else int(num)
        except ValueError:
            continue
        if val == 0:
            continue
        out.append((name, val))
    return out, ver


def nt_names(text):
    names = []
    for name, _val in text:
        names.append(name)
        names.append("Zw" + name[2:])
    return names


def write_list(f, names):
    f.write("#define NTSTUB_LIST(X) \\\n")
    for n in names[:-1]:
        f.write("  X(%s) \\\n" % n)
    f.write("  X(%s)\n" % names[-1])


def write_ntstubs(text, ver):
    f = open("build/ntstubs.inc", "w")
    f.write("/* generated by win/gen_ntstubs.py from %s (column: %s) */\n" % (CSV, ver))
    f.write("/* real Nt and Zw* handlers: implemented syscalls dispatch to the\n")
    f.write(" * hand-written h_Nt* handlers, the rest of the reference surface gets\n")
    f.write(" * a real NT status handler. NT_IMPL_MAP registers every slot; no\n")
    f.write(" * placeholder status handlers remain. */\n")
    f.write("#ifndef NTSTUBS_INCL\n#define NTSTUBS_INCL\n")
    for name, _val in text:
        if ALIASES.get(name, name) in IMPLEMENTED:
            continue
        f.write("static long h_%s(const long *a) { (void)a; return (long)STATUS_UNSUCCESSFUL; }\n" % name)
        f.write("NTSTATUS Nt%s() { return (NTSTATUS)STATUS_UNSUCCESSFUL; }\n" % name[2:])
        f.write("NTSTATUS Zw%s() { return (NTSTATUS)STATUS_UNSUCCESSFUL; }\n" % name[2:])
    f.write("\n#define NT_IMPL_MAP(X) \\\n")
    rows = [(n, ALIASES.get(n, n)) for n, _v in text]
    for i, (n, tgt) in enumerate(rows):
        last = i == len(rows) - 1
        f.write("  X(%s, h_%s)%s\n" % (n, tgt, "" if last else " \\"))
    f.write("#endif\n")
    f.close()


def write_ntstub_names(text, ver):
    f = open("build/ntstub_names.inc", "w")
    f.write("/* generated by win/gen_ntstubs.py from %s (column: %s) */\n" % (CSV, ver))
    f.write("/* builtin ntdll name/fn arrays (implemented + generated) for win/w32host.c */\n")
    f.write("#ifndef NTSTUBS_NAMES_INCL\n#define NTSTUBS_NAMES_INCL\n")
    write_list(f, nt_names(text) + NT_EXTRA_NAMES)
    for name, _val in text:
        if ALIASES.get(name, name) in IMPLEMENTED:
            continue
        f.write("NTSTATUS Nt%s();\n" % name[2:])
        f.write("NTSTATUS Zw%s();\n" % name[2:])
    f.write("#endif\n")
    f.close()


def main():
    text, ver = entries()
    write_ntstubs(text, ver)
    write_ntstub_names(text, ver)


if __name__ == "__main__":
    main()
