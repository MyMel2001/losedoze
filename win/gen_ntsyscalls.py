#!/usr/bin/env python3
"""Generate build/ntsyscalls.inc from windows-syscalls nt.csv (j00ru tables).

Reference data only: syscall numbers of the NT surface we are reimplementing.
Column: last Windows version in the table (newest). Our ntdll dispatch table is
indexed by these numbers (handlers registered for the implemented subset).
"""
import csv
import sys

CSV = "windows-syscalls/x64/csv/nt.csv"

def main(out_path):
    with open(CSV, newline="") as f:
        rows = list(csv.reader(f))
    header, body = rows[0], rows[1:]
    col = len(header) - 1  # newest version column
    ver = header[col]
    entries = []
    for r in body:
        if not r or not r[0].startswith("Nt"):
            continue
        name = r[0].strip()
        num = (r[col] if col < len(r) else "").strip()
        if not num:
            continue
        try:
            val = int(num, 16) if num.lower().startswith("0x") else int(num)
        except ValueError:
            continue
        if val == 0:  # syscall not present in this version
            continue
        entries.append((name, val))
    mx = max(v for _, v in entries)
    with open(out_path, "w") as o:
        o.write("/* generated by win/gen_ntsyscalls.py from %s (column: %s) */\n" % (CSV, ver))
        o.write("/* reference syscall numbers (j00ru windows-syscalls); original code here */\n")
        o.write("#define NT_NR_MAX 0x%x\n" % (mx + 1))
        o.write("#define NT_SYSCALL_LIST(X) \\\n")
        for name, val in entries:
            o.write("  X(%s, 0x%03x) \\\n" % (name, val))
        o.write("\n#define NT_SYSCALL_COUNT %d\n" % len(entries))

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "build/ntsyscalls.inc")
